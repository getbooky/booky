// BuildPlugin writes a ready-to-install plugin zip for one device: extract
// it and drop the resulting booky.koplugin folder into KOReader's plugins
// directory; it syncs against serverURL with the device's own token.
// Everything device-specific lives in the generated config.lua; the plugin
// code itself is static.
//
// The entries sit at the zip root on purpose: the download is served as
// booky.koplugin.zip, so the folder desktop extractors wrap the contents in
// is named booky.koplugin — the exact folder to copy. A folder inside the
// zip would come out nested one level deeper on Windows and most GUI tools.
func (s *Store) BuildPlugin(w io.Writer, d *Device, serverURL string) error {
	serverURL = strings.TrimRight(strings.TrimSpace(serverURL), "/")
	if serverURL == "" {
		return fmt.Errorf("set the server URL first — the plugin needs to know where Booky lives")
	}
	zw := zip.NewWriter(w)
	files := map[string]string{
		"_meta.lua":           metaLua,
		"main.lua":            mainLua,
		"booky_readalong.lua": readAlongLua,
		"booky_stretch.lua":   stretchLua,
		"config.lua":          configLua(d, serverURL),
	}
	// deterministic order keeps zips byte-comparable for the same inputs
	for _, name := range []string{"_meta.lua", "main.lua", "booky_readalong.lua", "booky_stretch.lua", "config.lua"} {
		f, err := zw.Create(name)
		if err != nil {
			return err
		}
		if _, err := f.Write([]byte(files[name])); err != nil {
			return err
		}
	}
	return zw.Close()
}

// configLua renders the per-device settings. Values are emitted as Lua
// literals; the token and URL are hex/URL-safe by construction.
func configLua(d *Device, serverURL string) string {
	auto, _ := json.Marshal(d.AutoIDs) //nolint:errcheck // []int64 cannot fail
	libs, _ := json.Marshal(d.TagIDs)
	return fmt.Sprintf(`-- Generated by Booky for device %q — do not edit; rebuild from
-- Settings → KoReader devices instead.
-- The download folder is chosen on-device (Booky → Download folder) and kept
-- in KOReader's own settings, so it survives plugin rebuilds.
return {
    server_url = %q,
    token = %q,
    device_name = %q,
    -- JSON arrays of tag ids (decoded in main.lua). The keys keep their old
    -- "libraries" names so plugins already on devices read them unchanged.
    libraries = %q,
    auto_libraries = %q,
}
`, d.Name, serverURL, d.Token, d.Name, string(libs), string(auto))
}

